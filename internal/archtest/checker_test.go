// writeTree creates files (slash-separated paths) under a fresh temp dir.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, src := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(src), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// TestCheckerDetectsViolations proves the checker is not vacuous: each kind
// of violation in a synthetic module is reported, and allowed imports are not.
func TestCheckerDetectsViolations(t *testing.T) {
	mod := ModulePath + "/"
	root := writeTree(t, map[string]string{
		"internal/arn/a.go":                    "package arn\nimport _ \"" + mod + "internal/model\"\n",
		"internal/model/m.go":                  "package model\nimport (\n_ \"os\"\n_ \"strings\"\n_ \"" + mod + "internal/arn\"\n)\n",
		"internal/model/m_test.go":             "package model\nimport (\n_ \"os\"\n_ \"pgregory.net/rapid\"\n_ \"os/exec\"\n)\n",
		"internal/eval/e.go":                   "package eval\nimport _ \"k8s.io/apimachinery/pkg/util\"\n",
		"internal/collect/terraform/plan/p.go": "package plan\nimport _ \"os/exec\"\n",
		"internal/collect/awslive/l.go":        "package awslive\nimport _ \"os/exec\"\n",
		"internal/unknown/u.go":                "package unknown\n",
		"testdata/ignored/x.go":                "package x\nimport _ \"unsafe\"\n",
	})
	rules := []*Rule{
		{Package: "internal/arn", Layer: LayerCore},
		{Package: "internal/model", Layer: LayerCore, Internal: []string{"internal/arn"}},
		{Package: "internal/eval", Layer: LayerCore, External: []string{"k8s.io/api"}},
		{Package: "internal/collect/terraform/plan", Layer: LayerIO, ExtraStd: []string{"os/exec"}},
		{Package: "internal/collect/awslive", Layer: LayerIO},
	}
	vs, err := Check(root, rules)
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, v := range vs {
		got = append(got, v.File+"|"+v.Import)
	}
	want := []string{
		"internal/arn/a.go|" + mod + "internal/model",     // leaf imports module package
		"internal/collect/awslive/l.go|os/exec",           // os/exec outside the one exception
		"internal/eval/e.go|k8s.io/apimachinery/pkg/util", // "k8s.io/api" must not match apimachinery
		"internal/model/m.go|os",                          // I/O in core
		"internal/model/m_test.go|os/exec",                // denied even in tests
		"internal/unknown/u.go|",                          // package without a row
	}
	slices.Sort(got)
	if !slices.Equal(got, want) {
		t.Fatalf("violations:\n got  %s\n want %s", strings.Join(got, "\n      "), strings.Join(want, "\n      "))
	}
}

func TestReplaceAndExtractRegion(t *testing.T) {
	text := "a\n# BEGIN GENERATED: r (x)\nold\n# END GENERATED: r\nz\n"
	out, err := ReplaceRegion(text, "r", "new1\nnew2\n")
	if err != nil {
		t.Fatal(err)
	}
	if want := "a\n# BEGIN GENERATED: r (x)\nnew1\nnew2\n# END GENERATED: r\nz\n"; out != want {
		t.Fatalf("ReplaceRegion = %q, want %q", out, want)
	}
	got, err := ExtractRegion(out, "r")
	if err != nil || got != "new1\nnew2\n" {
		t.Fatalf("ExtractRegion = %q, %v", got, err)
	}
	if _, err := ExtractRegion("no markers", "r"); err == nil {
		t.Fatal("expected an error for missing markers")
	}
}

func TestCountLinesAndGenerated(t *testing.T) {
	for _, c := range []struct {
		in   string
		want int
	}{{"", 0}, {"a", 1}, {"a\n", 1}, {"a\nb", 2}, {"a\nb\n", 2}} {
		if got := countLines([]byte(c.in)); got != c.want {
			t.Errorf("countLines(%q) = %d, want %d", c.in, got, c.want)
		}
	}
	if !isGenerated("// Code generated by x. DO NOT EDIT.\n\npackage p\n") {
		t.Error("generated header not detected")
	}
	if isGenerated("package p\n// Code generated by x. DO NOT EDIT.\n") {
		t.Error("header after package clause must not count")
	}
}
