<#
.SYNOPSIS
  Regenerates a committed Terraform plan JSON with real "terraform show -json"
  output, without any AWS account.

.DESCRIPTION
  Copies a Terraform configuration directory to a fresh temporary directory
  (the source is never modified), adds mock_override.tf with fake credentials
  and the AWS provider's skip_* settings, then runs terraform init,
  terraform plan -refresh=false and terraform show -json. Nothing is applied
  and no AWS API is called: the configurations have no data sources that
  need AWS.

  -Variant regenerates tests/fixtures/13_module_for_each/<variant>/plan.json.
  -Source and -Out regenerate any other plan, such as the plan collector's
  test data (internal/collect/terraform/plan/testdata/*/plan.json).

  Requires Terraform on PATH and network access to registry.terraform.io for
  the hashicorp/aws provider. Review the resulting diff before committing.

.EXAMPLE
  ./scripts/generate-fixture-plan.ps1 -Variant vulnerable
  ./scripts/generate-fixture-plan.ps1 -Source internal/collect/terraform/plan/testdata/for_each_map/terraform -Out internal/collect/terraform/plan/testdata/for_each_map/plan.json
#>
param(
  [ValidateSet('vulnerable', 'fixed')][string]$Variant,
  [string]$Source,
  [string]$Out
)
$ErrorActionPreference = 'Stop'

$repo = Split-Path -Parent $PSScriptRoot
if ($Variant) {
  $fixture = Join-Path $repo "tests/fixtures/13_module_for_each/$Variant"
  $Source = Join-Path $fixture 'terraform'
  $Out = Join-Path $fixture 'plan.json'
} elseif (-not ($Source -and $Out)) {
  throw 'give -Variant, or both -Source and -Out'
} else {
  $Source = Join-Path $repo $Source
  $Out = Join-Path $repo $Out
}
$work = Join-Path ([IO.Path]::GetTempPath()) ("clapa-plan-" + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $work | Out-Null
Copy-Item -Recurse -Path (Join-Path $Source '*') -Destination $work

@'
# Generated by scripts/generate-fixture-plan.ps1: fake credentials only, so
# that "terraform plan" runs without an AWS account. Never committed.
provider "aws" {
  access_key                  = "mock-access-key"
  secret_key                  = "mock-secret-key"
  skip_credentials_validation = true
  skip_requesting_account_id  = true
  skip_metadata_api_check     = true
  skip_region_validation      = true
  # allowed_account_ids needs the real account ID, which skip_requesting_account_id
  # prevents the provider from looking up; the fixture's clapa.yaml sets the account.
  allowed_account_ids = null
}
'@ | Set-Content -Encoding ascii -Path (Join-Path $work 'mock_override.tf')

$env:TF_IN_AUTOMATION = '1'
$env:CHECKPOINT_DISABLE = '1'
# cmd /c keeps terraform's stderr as text (PowerShell 5.1 would wrap it as errors).
cmd /c "terraform -chdir=`"$work`" init -input=false -no-color 2>&1" | Out-Host
if ($LASTEXITCODE -ne 0) { throw 'terraform init failed' }
cmd /c "terraform -chdir=`"$work`" plan -input=false -refresh=false -no-color -out=plan.tfplan 2>&1" | Out-Host
if ($LASTEXITCODE -ne 0) { throw 'terraform plan failed' }
$json = cmd /c "terraform -chdir=`"$work`" show -json plan.tfplan"
if ($LASTEXITCODE -ne 0) { throw 'terraform show failed' }

# UTF-8 without BOM and LF, like every other fixture file.
[IO.File]::WriteAllText($Out, (($json -join "`n") + "`n"), (New-Object Text.UTF8Encoding($false)))
Write-Host "wrote $Out"
Get-Content (Join-Path $work '.terraform.lock.hcl') | Select-String 'provider|version' | Out-Host
Remove-Item -Recurse -Force -LiteralPath $work
